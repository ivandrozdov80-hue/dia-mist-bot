def send_funny_review_prompt(user_id, send_func):
    """
    Отправляет одно из шуточных сообщений с приглашением оставить отзыв.
    Внизу будет основное меню с кнопкой «⭐ Отзывы».
    
    Args:
        user_id (int): ID пользователя
        send_func (callable): Функция отправки сообщения
    """
    message = random.choice(FUNNY_REVIEW_MESSAGES)
    send_func(user_id, message, keyboard=kb.get_main_keyboard())


